    private val enDefaults = listOf("the", "I", "you", "a", "to")
    private val ruDefaults = listOf("я", "не", "это", "что", "как")

    fun nextWords(previousWord: String?, language: InputLanguage, limit: Int = 3): List<String> {
        val key = previousWord?.lowercase()?.trim().orEmpty()
        val table = when (language) {
            InputLanguage.EN -> en
            InputLanguage.RU -> ru
        }
        val defaults = when (language) {
            InputLanguage.EN -> enDefaults
            InputLanguage.RU -> ruDefaults
        }
        val raw = if (key.isEmpty()) {
            defaults
        } else {
            val hits = table[key].orEmpty()
            if (hits.isNotEmpty()) hits else defaults
        }
        return ProfanityLexicon.preferNeutral(raw, language).take(limit)
    }
