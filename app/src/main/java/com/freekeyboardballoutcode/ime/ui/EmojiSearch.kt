    fun filter(emoji: List<String>, query: String): List<String> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return emoji
        return emoji.filter { glyph ->
            glyph.contains(q) ||
                aliases[glyph].orEmpty().any { alias -> alias.contains(q) || q.contains(alias) }
        }
    }

    fun searchAll(allEmoji: List<String>, query: String, categoryTitleHits: List<String>): List<String> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return allEmoji
        val fromAliases = filter(allEmoji, q)
        return (categoryTitleHits + fromAliases).distinct()
    }
